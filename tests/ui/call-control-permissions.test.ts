import { expect, test } from "bun:test";
const commands = [
  "set_call_muted",
  "set_call_held",
  "transfer_call",
  "start_consultation",
  "switch_call",
  "cancel_consultation",
  "complete_transfer",
];
const base = "apps/desktop/src-tauri/";
test("all seven controls have main-only authority and explicit command registration", async () => {
  const main = await Bun.file(base + "capabilities/main.json").json();
  const settings = await Bun.file(base + "capabilities/settings.json").json();
  const handlers = await Bun.file(base + "src/lib.rs").text();
  const manifest = await Bun.file(base + "build.rs").text();
  for (const command of commands) {
    const permission = "allow-" + command.replaceAll("_", "-");
    const generated = await Bun.file(
      base + "permissions/autogenerated/" + command + ".toml",
    ).text();
    expect(generated).toContain('commands.allow = ["' + command + '"]');
    expect(main.permissions).toContain(permission);
    expect(settings.permissions).not.toContain(permission);
    expect(handlers).toContain("commands::" + command);
    expect(manifest).toContain('"' + command + '"');
  }
});
