//! Generate the frontend IPC contract from its canonical Rust types.

use phone_core::{
    AboutLink, AccountConfig, AccountSnapshot, AppInfo, AudioDevice, AudioDevices, AudioMode,
    CallEvent, CallEventKind, CallState, CallerIdentity, DesktopSettings, EngineSnapshot,
    ErrorCode, NotificationPermission, PhoneError, RegistrationState, SoundSettings,
    TelephonyStatus,
};
use phone_core::{
    CallDirection, CallOutcome, ContactReference, HistoryEntry, HistoryFilter, HistoryPage,
    HistoryQuery,
};
use phone_core::{Contact, ContactPhone, ContactSource, ContactsPermission, ContactsSnapshot};
use std::{fs, path::Path};
use ts_rs::{Config, TS};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let destination = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../apps/desktop/src/lib/generated/AppInfo.ts");
    let config = Config::default();
    let types = [
        TelephonyStatus::decl(&config),
        AppInfo::decl(&config),
        AboutLink::decl(&config),
        AudioMode::decl(&config),
        SoundSettings::decl(&config),
        AudioDevice::decl(&config),
        AudioDevices::decl(&config),
        AccountConfig::decl(&config),
        ErrorCode::decl(&config),
        PhoneError::decl(&config),
        RegistrationState::decl(&config),
        CallState::decl(&config),
        CallEventKind::decl(&config),
        CallEvent::decl(&config),
        CallerIdentity::decl(&config),
        AccountSnapshot::decl(&config),
        EngineSnapshot::decl(&config),
        NotificationPermission::decl(&config),
        DesktopSettings::decl(&config),
        ContactSource::decl(&config),
        ContactsPermission::decl(&config),
        ContactPhone::decl(&config),
        Contact::decl(&config),
        ContactsSnapshot::decl(&config),
        ContactReference::decl(&config),
        CallDirection::decl(&config),
        CallOutcome::decl(&config),
        HistoryEntry::decl(&config),
        HistoryFilter::decl(&config),
        HistoryQuery::decl(&config),
        HistoryPage::decl(&config),
    ];
    let declarations = format!(
        "// Generated by bun run types:generate. Do not edit.\n\n{}\n",
        types.map(|t| format!("export {t}")).join("\n\n")
    );
    fs::create_dir_all(destination.parent().ok_or("Missing export directory")?)?;
    let normalized = declarations
        .lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n");
    fs::write(destination, format!("{normalized}\n"))?;
    Ok(())
}
